import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {exportMap, priority} from './migrate-root-imports.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const map = exportMap(root, true);
let output = '/** Compatibility barrel. Generated by scripts/generate-root-barrel.mjs.\n * New code imports canonical subpaths; ./native is intentionally separate.\n * Per-specifier JSDoc preserves IDE deprecation without deprecating canonical bindings.\n */\n';
for (const sub of priority) {
    for (const type of [false, true]) {
        const names = [...map].filter(([, home]) => home.sub === sub && home.type === type).map(([name]) => name);
        if (!names.length) continue;
        output += `\nexport ${type ? 'type ' : ''}{\n`;
        for (const name of names) output += `    /** @deprecated Import from 'wenay-react2/${sub}' instead. */\n    ${name},\n`;
        output += `} from './${sub}/index.js';\n`;
    }
}
const file = path.join(root, 'src/api.tsx');
if (process.argv.includes('--write')) fs.writeFileSync(file, output);
else if (fs.readFileSync(file, 'utf8').replaceAll('\r\n', '\n') !== output) {
    console.error('Root barrel is stale; run node scripts/generate-root-barrel.mjs --write');
    process.exitCode = 1;
}
